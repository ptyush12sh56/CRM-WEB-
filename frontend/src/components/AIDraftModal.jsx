export default function AIDraftModal({ contact, draft, loading, error, onClose }) {
  return (
    <div className="overlay" onClick={(e) => e.target === e.currentTarget && onClose()}>
      <div className="modal">
        <h3>AI follow-up draft</h3>
        {loading && <p className="ai-note">Drafting a follow-up for {contact.name}…</p>}
        {error && <div className="form-error">{error}</div>}
        {draft && (
          <>
            <p style={{ fontWeight: 600, marginBottom: 6 }}>{draft.subject}</p>
            <div className="ai-output">{draft.body}</div>
            <p className="ai-note">
              {draft.generated_by === 'ai'
                ? 'Generated by the connected AI model.'
                : 'Generated from a stage-based template (set ANTHROPIC_API_KEY on the backend for live AI drafts).'}
            </p>
          </>
        )}
        <div className="modal-actions">
          <button className="btn-sm btn-accent" onClick={onClose}>Close</button>
        </div>
      </div>
    </div>
  )
}
